#!/usr/bin/env node
/**
 * probe-p300.mjs. THE PHASE 300 APP RUN: what a first read costs the person
 * waiting (build/p300/SPEC.md §6, the Phase 300 entry in docs/BACKLOG.md).
 *
 * ONE Electron through build/electron-run.mjs's `withElectron`, on a scratch
 * profile, a scratch HOME and the tmux socket build/harness-socket.mjs hands it.
 * **Nothing is spawned, no agent runs and no token is spent**: every session is a
 * seeded manifest row and every record it reads is a record it wrote itself.
 *
 * ## A PHOTOGRAPH IS FORBIDDEN AND `npm run shot` NEVER RUNS
 *
 * Every number below comes out of a channel, not out of an image. The launch
 * does go through `GMUX_SHOT`, because that is the branch of
 * `src/main/harness/index.ts:637` that reaches `seedOverviewSessions()` and it
 * is the only door a probe has to a seeded manifest, and `GMUX_SHOT_JS` is the
 * read-back knob (`src/main/harness/shot.ts:469-479`: "A screenshot proves a
 * thing was drawn; this is how a verifier proves a thing is TRUE"). The PNG it
 * writes is a scratch byte under this run's own directory, it is never read,
 * never compared and never kept, and the same pattern is what
 * `build/p276/probe-p276.mjs:1052-1060` uses. **No reading in this file comes
 * from an image.**
 *
 * ## IT READS NOTHING OF THE OPERATOR'S, and that is not a courtesy
 *
 * Phase 300's numbers were measured on 2026-09-19 over his own store — 26,312
 * codex records at 11.76 GB, the largest 959.5 MiB, and claude records under
 * 2,776 project directories — and they are **not re-measurable here**. Reading a
 * 959 MiB file of his conversation to check a timing would be slow and would be
 * a privacy breach. So:
 *
 *   - every codex record is SYNTHESISED from the committed fixture by
 *     `build/p300/generate-codex-records.mjs`, at the four sizes his measured
 *     distribution names plus a second 200 MiB record for the page arm, and
 *     every generated byte is deleted in a `finally`. A synthesised record is
 *     100 percent `item_completed` padding outside its 30 fixture lines, where
 *     his own 186.8 MiB record is 58 percent, so every number here is a number
 *     on the heaviest shape and not on his;
 *   - the claude project directories C5 is about are EMPTY directories this run
 *     creates under its scratch HOME, at a count it names;
 *   - `HOME` is redirected for the whole launch, so a resolver that went looking
 *     under the real home would find nothing there at all.
 *
 * ## THE INSTRUMENT, and how it is read
 *
 * **A 20 ms ping from OUTSIDE main.** A loop in the renderer calls the existing
 * cheap bridge door `window.gmux.settingsGet()` (`src/preload/index.ts:192` →
 * `settings:get`) every `PING_PERIOD_MS` and records the worst round trip while
 * an ask runs. `overview/ipc.ts` registers `invoke` handlers, so for the length
 * of one row's read main answers nothing at all — not this channel, not the
 * window, not the tmux poll — and that round trip is exactly what a person
 * feels. **No new channel, no new `GMUX_*` name and no new harness smoke
 * mode**, so `gate:contract` does not move.
 *
 * THE PINGER IS DRAINED BEFORE ITS WORST IS READ, and the first build did not,
 * which graded every reading one label late. The ping stuck behind a read
 * resolves one task AFTER the invoke that held it, so a `worst` read the moment
 * the invoke resolved was the PREVIOUS reading's stall, and the Phase 300
 * verifier's judge re-derived from the builders' own four runs that
 * `worstPing(N) = wall(N-1) - about 20 ms` on every blocking pair. So `measure`
 * now sends one more ping after the invoke resolves and awaits it: replies come
 * back in order, so when that ping lands the stuck one has landed too and its
 * wait is in `worst`. It drains once BEFORE the reset as well, so a ping in
 * flight from the previous reading cannot carry into this one.
 *
 * WHAT THE WORST PING MEASURES, so the number is read right: exactly one ping
 * is stuck behind a read, the first one sent after the invoke reached main, and
 * it was sent up to one ping period after that, so its wait is the read's wall
 * MINUS a phase term of up to `PING_PERIOD_MS` plus one round trip. Two runs of
 * the same code can therefore differ by up to about a ping period in this
 * column from phase alone. That is the instrument's RESOLUTION and it is why
 * the grading below reads a ping-graded delta inside one ping period as "not
 * resolved" rather than as a change in either direction.
 *
 * ## THE READINGS, and how each is graded against the parent
 *
 *   1  first-big         the FIRST counts ask over the 200 MiB record
 *   2  first-huge        the same over the 960 MiB record
 *   3  page-after-sheet  Catch Me Up's read (`overview:sessions`) of the 960
 *                        MiB record the sheet has just counted. Today, and at
 *                        HEAD, this is a stat and a tail, because the page
 *                        resumes from the watermark the counts read wrote. The
 *                        flag the fix round removed forced a full re-read here,
 *                        and this arm is what would have shown it.
 *   4  page-first        Catch Me Up's read of a SECOND 200 MiB record that no
 *                        counts read has touched: the page's own full read,
 *                        which the first build made 31 to 55 percent slower on
 *                        every large codex record while its probe never took
 *                        a page reading at all
 *   5  first-small       the first counts ask over the p50 and p99 records
 *                        together, the two sizes a person meets constantly.
 *                        The first build folded these two first reads into
 *                        its "warm" reading, which was then not warm.
 *   6  warm              a warm counts pass over the four codex rows, every
 *                        watermark satisfied. This is the ask a person makes
 *                        all day and it must not have got slower.
 *   7  c5-first          a claude row with no record, asked once — UNCHANGED by
 *                        this phase by design (§4.3's CORRECTION 3)
 *   8  c5-repeat         the same row asked AGAIN inside the window, which is
 *                        C5's own reading and the one the cache is for
 *   9  pass-161          the wall time of a 161-row pass, asked 100 ids at a
 *                        time the way `session-manager-slice.ts` asks. Every
 *                        row is a claude row with no record, the verifier's own
 *                        575-of-659 ms shape. The FIRST pass is unchanged at
 *                        HEAD, because 161 distinct ids share nothing within
 *                        one pass, and
 *  10  pass-161-repeat   the same pass inside the window, where the cache shows
 *  11  heartbeat         the worst ping over the whole run, printed and not
 *                        graded
 *
 * A PASS is graded on its WALL, because a pass is 161 invokes and its wall is
 * the number; everything else is graded on its DRAINED WORST PING, which is
 * what a person feels, with the wall printed beside it. Against the parent:
 *
 *   - `P300_HIT_PARENT` may name SEVERAL parent readings files, comma
 *     separated. A reading's floor is then the WORST of the parent's own
 *     readings of it, and the parent's band is printed. Today's build measured
 *     more than once gives a band, and a HEAD reading inside that band is not
 *     distinguishable from today; that is the operator's rule read plainly,
 *     and it is not a tolerance because the band is measured and never assumed.
 *     With one parent file the floor is that one reading.
 *   - a ping-graded delta inside one `PING_PERIOD_MS` is "not resolved", per
 *     the phase term above. A wall-graded delta has no phase term and gets no
 *     such floor.
 *
 * Every reading carries the COUNTS the ask came back with. **A count that moves
 * fails the run whichever way it moves**: this phase is about time, and a
 * changed count is a regression that belongs to Phase 299. For the page arms
 * the counts are the turns drawn, each turn's git mark and its outside flag,
 * which is what the path index feeds.
 *
 * ## The pin, taken by the checkout's OWN conformance script
 *
 * The prefilter must read `head` and never `wide` on these records, because a
 * wide head is a 4 MiB window per line and measures a different thing than a
 * person pays. The pin is taken through `build/conformance-overview.mjs --real`
 * of the checkout under measurement, run with that checkout's cwd, so a parent
 * arm's pin is a parent reading. A checkout whose script does not print the
 * prefilter mode — the parent's does not — pins the turn count instead and says
 * so; the two arms' turn counts must agree.
 *
 * ## Environment
 *
 *   GMUX_TMUX_SOCKET       the scratch socket; build/harness-socket.mjs sets it
 *   GMUX_HARNESS_DIR       the scratch directory; the same wrapper sets it
 *   P300_PARENT_CHECKOUT   a BUILT worktree at the parent commit. Optional; it
 *                          moves the app's cwd, its out/ and the pin's script
 *   P300_OUT_DIR           where the readings go. `out/p300` by default, and
 *                          `out/p300-parent` under the parent knob
 *   P300_HIT_PARENT        one or more parent readings.json, comma separated.
 *                          With it, every reading is graded against the
 *                          parent's and a reading that got WORSE fails the run
 *   P300_SIZES             a subset of p50,p99,big,huge,page. All five by
 *                          default; an arm whose record is missing is skipped
 *                          and named
 *   P300_CLAUDE_DIRS       how many empty claude project directories to create.
 *                          2776 by default, which is what his home held on
 *                          2026-09-19
 *
 * ## Usage, from the worktree root
 *
 *   npm run probe:p300
 *
 *   The parent, already built:
 *   P300_PARENT_CHECKOUT=/path/to/parent P300_OUT_DIR=out/p300-parent \
 *     node build/harness-socket.mjs --fresh gmux-p300 'node build/p300/probe-p300.mjs'
 *
 *   Then HEAD, graded against it (two parent runs, interleaved, is the shape):
 *   P300_HIT_PARENT=out/p300-parent-1/readings.json,out/p300-parent-2/readings.json \
 *     node build/harness-socket.mjs --fresh gmux-p300 'node build/p300/probe-p300.mjs'
 *
 * Exit 0 when every reading came back and none is worse than the parent's. 1
 * when a reading is worse or a count moved. 2 when the probe refuses to run.
 */

