/**
 * C5's OWN FIXTURE: the claude projects directory, at the width that makes the
 * finding real.
 *
 * `reader/resolve.ts`'s claude arm accepts `<id>.jsonl` under ANY entry of
 * `~/.claude/projects`, so a row whose record is not at the direct path stats
 * every entry on every ask. His home held 2,776 directories on 2026-09-19 at a
 * median of 19.5 ms per scan. These are EMPTY directories with names of the
 * same shape — the dash encoding `dashEncodeClaudeCwd` writes — and they hold no
 * conversation of anybody's.
 */
function buildClaudeProjects(n) {
  const projects = join(home, '.claude', 'projects');
  mkdirSync(projects, { recursive: true });
  for (let i = 0; i < n; i += 1) {
    mkdirSync(join(projects, `-Users-p300-scratch-project-${String(i).padStart(5, '0')}`), {
      recursive: true
    });
  }
  // The three non-directory entries his own directory holds, because the
  // resolver stats a `<id>.jsonl` path under every entry WHATEVER it is, and a
  // fixture of directories alone would not exercise that.
  for (const stray of ['.DS_Store', '.cursorindexingignore']) {
    writeFileSync(join(projects, stray), '', 'utf8');
  }
  return projects;
}

// ---------------------------------------------------------------------------
// The measuring expression, evaluated in the DRIVEN window by GMUX_SHOT_JS
