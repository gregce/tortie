/**
 * One expression. It starts the ping, asks the counts channel the way the sheet
 * asks it and the page channel the way Catch Me Up asks it, and answers one
 * JSON object.
 *
 * IT IS WRITTEN AS A STRING because that is the shape `GMUX_SHOT_JS` takes. The
 * ids come from `window.gmux.sessions.list()` and are matched by the NAME the
 * seed gave them, because `overview-seed.ts` mints a fresh `randomUUID()` for
 * every row and no probe can know it in advance.
 */
function measureJs(spec) {
  return `(async () => {
  const g = window.gmux;
  const wait = (ms) => new Promise((r) => setTimeout(r, ms));
  const notes = [];
  const PING_PERIOD_MS = ${String(PING_PERIOD_MS)};
  try {
    // THE PING, FROM OUTSIDE MAIN. settings:get is an existing cheap invoke and
    // the loop adds no channel of its own. What it measures is the round trip a
    // person's own keystroke would take while main is inside one row's read.
    const ping = { worst: 0, n: 0, running: true };
    const pinger = (async () => {
      while (ping.running) {
        const t = performance.now();
        try { await g.settingsGet(); } catch (e) { /* the window may be closing */ }
        const dt = performance.now() - t;
        if (dt > ping.worst) ping.worst = dt;
        ping.n += 1;
        await wait(PING_PERIOD_MS);
      }
    })();
    // THE DRAIN. One ping sent NOW and awaited. Replies come back in order, so
    // when this one lands every ping sent before it has landed too, including
    // the one stuck behind whatever main was just doing, and the pinger loop
    // has already folded that one's wait into ping.worst.
    const drain = async () => { try { await g.settingsGet(); } catch (e) { /* as above */ } };
    const heartbeat = { worst: 0 };
    const round = (x) => Math.round(x * 100) / 100;

    // Counts as ONE string per reading, so a moved count is a string that
    // differs. The counts channel answers per-session numbers; the page channel
    // answers turns with git marks, which is what the path index feeds.
    const countsOfActivity = (answer) =>
      (answer && answer.sessions ? answer.sessions : [])
        .map((s) => [s.userMessages, s.agentMessages, s.coverage, s.reason, s.lastMessageAt, s.lastBy]
          .map((v) => (v === undefined ? 'undefined' : JSON.stringify(v))).join('/'))
        .join(' ');
    const countsOfPage = (answer) =>
      (answer && answer.sessions ? answer.sessions : [])
        .map((s) => 'turns=' + s.turns.length + ' line=' + s.line + ' ' +
          s.turns.map((t) => JSON.stringify(t.git) + (t.namedOnlyOutside ? '!' : '')).join(','))
        .join(' ');

    const measure = async (label, fn, countsOf) => {
      await drain();
      ping.worst = 0;
      ping.n = 0;
      const t = performance.now();
      let answer = null;
      let error = null;
      try { answer = await fn(); } catch (e) { error = String(e && e.message ? e.message : e); }
      const wallMs = performance.now() - t;
      await drain();
      const worst = ping.worst;
      if (worst > heartbeat.worst) heartbeat.worst = worst;
      return {
        label,
        wallMs: round(wallMs),
        worstPingMs: round(worst),
        pings: ping.n,
        error,
        counts: countsOf(answer)
      };
    };

    // Let the app settle and the ping take a few samples before anything is
    // asked, so the first reading is not the boot.
    await wait(1500);

    const all = await g.sessions.list();
    const byName = new Map(all.map((s) => [s.name, s]));
    const need = ${JSON.stringify(spec.names)};
    const missing = need.filter((n) => !byName.has(n));
    if (missing.length > 0) {
      ping.running = false;
      await pinger;
      return { error: 'the seeded rows are not in the list: ' + missing.join(', '), listed: all.length };
    }
    const idOf = (n) => byName.get(n).id;
    const has = (n) => byName.has(n);
    const readings = [];
    const activity = (names) => g.overview.activity({ sessionIds: names.map(idOf) });
    const page = (name) => g.overview.sessions({ projectPath: ${JSON.stringify(spec.project)}, sessionIds: [idOf(name)] });

    // 1 and 2. THE FIRST ASK over each large record. One id per call, so the
    // reading is one row's read and not a pass.
    for (const one of ${JSON.stringify(spec.firstAsk)}) {
      readings.push(await measure('first-' + one, () => activity(['p300-codex-' + one]), countsOfActivity));
    }

    // 3. THE PAGE AFTER THE SHEET. Catch Me Up's read of the record the sheet
    // has just counted. A stat and a tail today; a flag that stamped the
    // counts read's watermark would make it a full read again, and this arm is
    // where that would show.
    if (has('p300-codex-huge')) {
      readings.push(await measure('page-after-sheet', () => page('p300-codex-huge'), countsOfPage));
    } else {
      notes.push('page-after-sheet skipped: no huge record in this run');
    }

    // 4. THE PAGE FIRST. Catch Me Up's read of a large record nothing has read:
    // the page's own full read, with the path index built.
    if (has('p300-codex-page')) {
      readings.push(await measure('page-first', () => page('p300-codex-page'), countsOfPage));
    } else {
      notes.push('page-first skipped: no page record in this run');
    }

    // 5. THE SMALL FIRST READS. p50 and p99 together, so that the warm pass
    // below is warm: the first build folded these two first reads into it.
    const small = ${JSON.stringify(spec.smallNames)};
    if (small.length > 0) {
      readings.push(await measure('first-small', () => activity(small), countsOfActivity));
    } else {
      notes.push('first-small skipped: no p50 or p99 record in this run');
    }

    // 6. THE WARM PASS. The four codex rows again, every watermark satisfied.
    // This is the ask a person makes all day and it must not have got slower.
    readings.push(await measure('warm', () => activity(${JSON.stringify(spec.codexNames)}), countsOfActivity));

    // 7 and 8. C5. A claude row with NO record: the first ask scans every
    // project directory, and the second must not.
    readings.push(await measure('c5-first', () => activity(['p300-claude-norecord']), countsOfActivity));
    readings.push(await measure('c5-repeat', () => activity(['p300-claude-norecord']), countsOfActivity));

    // 9 and 10. THE 161 ROW PASS, TWICE, asked 100 ids at a time the way the
    // sheet asks (session-manager-slice.ts against main's cap of 200). Every
    // filler is a claude row with no record, so the pass is the verifier's own
    // 575-of-659 ms shape. The FIRST pass is unchanged at HEAD and the SECOND
    // must fall. A pass is graded on its wall; its drained worst ping is read
    // the same way as every other reading's, so a block inside the pass shows.
    const fillers = all.filter((s) => s.name.startsWith('p300-filler-')).map((s) => s.id);
    const ids = fillers.slice(0, 161);
    for (const which of ['pass-161', 'pass-161-repeat']) {
      const r = await measure(which, async () => {
        let answered = 0;
        for (let i = 0; i < ids.length; i += 100) {
          const chunk = ids.slice(i, i + 100);
          const a = await g.overview.activity({ sessionIds: chunk });
          answered += (a && a.sessions ? a.sessions.length : 0);
        }
        return { answered };
      }, (a) => 'answered=' + String(a ? a.answered : null) + '/' + String(ids.length));
      if (ids.length !== 161 && r.error === null) r.error = 'only ' + ids.length + ' filler rows were seeded';
      readings.push(r);
    }

    ping.running = false;
    await pinger;
    return { readings, heartbeatWorstMs: round(heartbeat.worst), listed: all.length, notes };
  } catch (err) {
    return { error: String(err && err.message ? err.message : err), notes };
  }
})()`;
}

// ---------------------------------------------------------------------------
// The pin, through the checkout's own conformance script
// ---------------------------------------------------------------------------

/**
 * `build/conformance-overview.mjs --real` of the CHECKOUT under measurement,
 * run with that checkout as cwd, so a parent arm's pin is the parent's own
 * reading. It answers the prefilter mode when that script prints one (HEAD's
 * does, on the provider line) and the turn count always.
 */
function pinRecord(file) {
  const run = spawnSync(
    process.execPath,
    [join(checkout, 'build', 'conformance-overview.mjs'), '--real', file, '--provider', 'codex', '--repo', project],
    { encoding: 'utf8', cwd: checkout, maxBuffer: 256 * 1024 * 1024 }
  );
  const text = `${run.stdout ?? ''}${run.stderr ?? ''}`;
  const turns = /\b(\d+) turns\b/.exec(text);
  const prefilter = /, prefilter (\w+)/.exec(text);
  return {
    status: run.status,
    turns: turns === null ? null : Number(turns[1]),
    prefilter: prefilter === null ? null : prefilter[1]
  };
}

// ---------------------------------------------------------------------------
// The run
// ---------------------------------------------------------------------------

const problems = [];
let generated = null;
let report = null;
const pins = {};

try {
  say(`base ${base}, app from ${checkout}`);
  say(`claude project directories: ${String(claudeDirs)} (his home held 2,776 on 2026-09-19)`);
  const projectsDir = buildClaudeProjects(claudeDirs);

  say(`synthesising codex records ${sizes.join(', ')} under ${home}`);
  const t0 = Date.now();
  generated = generateCodexRecords({ home, sizes });
  for (const r of generated.records) {
    say(`  ${r.size.padEnd(5)} ${String(r.bytes).padStart(12)} bytes, ${String(r.lines)} lines`);
  }
  say(`generated in ${String(Date.now() - t0)} ms; every byte is deleted in this run's finally`);

  // THE PREFILTER MUST READ `head` AND NEVER `wide` on these records, asserted
  // through the CHECKOUT'S conformance script over the same files, so the
  // parent arm's pin is a parent reading and not HEAD's reader over the parent's
  // records. A checkout whose script prints no prefilter mode pins the turn
  // count and says so.
  for (const r of generated.records) {
    const pin = pinRecord(r.file);
    pins[r.size] = pin;
    if (pin.status !== 0 || pin.turns === null) {
      problems.push(`the ${r.size} record could not be pinned: the checkout's conformance script exited ${String(pin.status)}`);
      continue;
    }
    if (pin.prefilter === null) {
      say(`  ${r.size}: ${String(pin.turns)} turns; this checkout's script prints no prefilter mode, so the head pin is HEAD's to take`);
    } else if (pin.prefilter !== 'head') {
      problems.push(
        `the ${r.size} record read prefilter "${pin.prefilter}" and not "head". A wide head is a ` +
          '4 MiB window per line and measures a different thing than a person pays.'
      );
    } else {
      say(`  ${r.size}: ${String(pin.turns)} turns, prefilter head`);
    }
  }

  // The seed. The codex rows, one claude row with NO record, and enough filler
  // rows for a 161-row pass. Every filler is a claude row with no record, which
  // costs the read nothing and makes the pass measure C5's own loop.
  const seedRows = [
    ...seedRowsFor(generated, project),
    {
      name: 'p300-claude-norecord',
      agent: 'claude',
      // A conversation id that exists nowhere: the resolver falls off the end of
      // the fallback loop and answers `no-file`, which is C5's own case.
      agentSessionId: 'p300bbbb-0001-4000-8000-000000000000',
      cwd: project,
      createdAt: Date.now()
    }
  ];
  // THE 161 FILLER ROWS ARE CLAUDE ROWS WITH NO RECORD, and that choice is the
  // whole of readings 9 and 10.
  //
  // The verifier's warm pass over 161 rows cost 659 ms of which **575 ms was
  // inside the claude fallback loop**. A pass of shells would have measured the
  // orchestration and none of the finding. Each row carries a DISTINCT id that
  // exists nowhere, so at the parent every one of the 161 runs the loop over
  // all 2,776 directories, and at HEAD the FIRST pass is unchanged — 161
  // distinct ids share nothing within one pass, which is SPEC §4.3's
  // CORRECTION 3 — while the SECOND pass inside the window is one `statSync` a
  // row. Both passes are read, and the pair is the finding.
  for (let i = 0; i < 161; i += 1) {
    seedRows.push({
      name: `p300-filler-${String(i).padStart(3, '0')}`,
      agent: 'claude',
      agentSessionId: `p300cccc-${String(i).padStart(4, '0')}-4000-8000-000000000000`,
      cwd: project,
      createdAt: Date.now()
    });
  }
  const seedPath = join(root, 'overview-seed.json');
  writeFileSync(seedPath, JSON.stringify(seedRows), 'utf8');
  say(`seeding ${String(seedRows.length)} manifest rows through src/main/harness/overview-seed.ts`);

  const countsSizes = generated.records.filter((r) => r.size !== 'page');
  const js = measureJs({
    project,
    names: [...generated.records.map((r) => `p300-codex-${r.size}`), 'p300-claude-norecord'],
    firstAsk: countsSizes.filter((r) => r.size === 'big' || r.size === 'huge').map((r) => r.size),
    smallNames: countsSizes.filter((r) => r.size === 'p50' || r.size === 'p99').map((r) => `p300-codex-${r.size}`),
    codexNames: countsSizes.map((r) => `p300-codex-${r.size}`)
  });

  const png = join(outDir, `p300-${base}-scratch.png`);
  rmSync(png, { force: true });
  const { code, text } = await runElectron({
    label: `p300 ${base}`,
    userDataDir: profile,
    tmuxSocket: socket,
    cwd: checkout,
    env: {
      ...process.env,
      HOME: home,
      GMUX_TMUX_SOCKET: socket,
      GMUX_HARNESS_DIR: harnessDir,
      GMUX_SPECSTORY_NO_CLOUD: '1',
      // The seed's door. `src/main/harness/index.ts:665` is inside the
      // GMUX_SHOT branch, which is why this launch names one at all.
      GMUX_OVERVIEW_SEED: seedPath,
      GMUX_SHOT: png,
      // Open the project, and nothing else. The Catch Me Up page is NOT opened
      // by the drive: the page arms ask its channel themselves, in the order
      // the readings name, so the first reading is a first read.
      GMUX_SHOT_DRIVE: JSON.stringify({ projectPath: project }),
      GMUX_SHOT_JS: js,
      // Long enough for the drive to finish before the measurement starts, and
      // the measurement is what holds the app up rather than this number.
      GMUX_SHOT_DELAY_MS: '9000'
    },
    // withElectron ends the tree it started, and the scratch tmux server it was
    // handed, in a `finally` whatever happened here. This is the outer bound of
    // a HUNG run and not a budget: the 960 MiB record alone is under two
    // seconds of read and the run asks for several.
    ceilingMs: 8 * 60 * 1000,
    settleMs: 500
  });

  const marker = '[gmux-shot] probe ';
  const at = text.lastIndexOf(marker);
  if (at === -1) {
    problems.push('the window returned no reading at all. The probe measured nothing.');
  } else {
    let payload = text.slice(at + marker.length).split('\n')[0] ?? '';
    try {
      report = JSON.parse(payload);
      if (typeof report === 'string') report = JSON.parse(report);
    } catch (err) {
      problems.push(`the reading was not JSON: ${String(err)}`);
    }
  }
  if (code !== 0) say(`the app exited ${String(code)}; the readings below are what it printed first`);
  // The scratch PNG is never read and never kept.
  rmSync(png, { force: true });
  void projectsDir;
} catch (err) {
  problems.push(`the run threw: ${err instanceof Error ? err.message : String(err)}`);
} finally {
  // EVERY GENERATED BYTE, WHATEVER HAPPENED. The Electron and the scratch tmux
  // server are ended by build/electron-run.mjs's own `finally`; these are the
  // bytes this file wrote.
  if (generated !== null) {
    generated.remove();
    say('the synthesised codex records are gone');
  }
  rmSync(join(home, '.claude'), { recursive: true, force: true });
  say('the scratch claude projects directory is gone');
}

// ---------------------------------------------------------------------------
// The verdict
// ---------------------------------------------------------------------------

if (report !== null && report.error !== undefined && report.error !== null) {
  problems.push(`the window refused: ${String(report.error)}`);
}
for (const n of report?.notes ?? []) say(n);

const readings = report?.readings ?? [];
const pad = (v, w) => String(v).padEnd(w);
const num = (v, w) => String(v).padStart(w);
const gradedKey = (label) => (WALL_GRADED.has(label) ? 'wallMs' : 'worstPingMs');

process.stdout.write(`\nPhase 300, ${base}: what a first read costs the person waiting\n\n`);
process.stdout.write(
  pad('reading', 18) + num('wall ms', 10) + num('worst ping', 12) + num('pings', 8) + '  graded on   counts\n'
);
process.stdout.write('-'.repeat(120) + '\n');
for (const r of readings) {
  process.stdout.write(
    pad(r.label, 18) +
      num(r.wallMs, 10) +
      num(r.worstPingMs, 12) +
      num(r.pings, 8) +
      '  ' +
      pad(gradedKey(r.label) === 'wallMs' ? 'wall' : 'ping', 11) +
      ' ' +
      String(r.counts ?? '').slice(0, 60) +
      (r.error ? `  ERROR ${String(r.error)}` : '') +
      '\n'
  );
  if (r.error) problems.push(`${r.label}: ${String(r.error)}`);
  // The drain's own invariant: exactly one ping is stuck behind a read and it
  // was sent AFTER the read began, so its wait can never exceed the wall it
  // sat inside. A worst ping above its own wall is a ping that belongs to
  // another reading, which is the defect the drain exists to stop.
  if (typeof r.worstPingMs === 'number' && typeof r.wallMs === 'number' && r.worstPingMs > r.wallMs + PING_PERIOD_MS) {
    problems.push(
      `${r.label}: its worst ping (${String(r.worstPingMs)} ms) is above its own wall (${String(r.wallMs)} ms) by ` +
        'more than a ping period. A ping is stuck only behind the read it was sent into, so this reading is ' +
        "carrying another reading's stall and the drain has not held."
    );
  }
}
if (report?.heartbeatWorstMs !== undefined) {
  process.stdout.write(
    `\nthe worst ping over the whole run: ${String(report.heartbeatWorstMs)} ms ` +
      "(the verifier's heartbeat gap was 322 ms)\n"
  );
}

// C5's own clause, which needs no parent to judge: the SECOND ask of a row with
// no record must be cheaper than the first. The cache is of the ANSWER, the
// fallback's negative answer keyed by id, and this is what says it is there.
const c5First = readings.find((r) => r.label === 'c5-first');
const c5Repeat = readings.find((r) => r.label === 'c5-repeat');
if (c5First !== undefined && c5Repeat !== undefined) {
  process.stdout.write(
    `\nC5: the first ask of a claude row with no record cost ${String(c5First.wallMs)} ms and the ` +
      `second cost ${String(c5Repeat.wallMs)} ms\n`
  );
  if (c5Repeat.wallMs > c5First.wallMs) {
    problems.push(
      `C5: the REPEAT ask (${String(c5Repeat.wallMs)} ms) cost more than the first ` +
        `(${String(c5First.wallMs)} ms). The whole of option 3 is that it costs one statSync.`
    );
  }
}

// The parent, if one or more runs were handed over. Every reading equal or
// lower at HEAD, against the WORST of the parent's own readings of it.
const hitParent = (process.env['P300_HIT_PARENT'] ?? '').trim();
if (hitParent !== '') {
  const parentFiles = hitParent.split(',').map((f) => resolve(repoRoot, f.trim())).filter((f) => f !== '');
  const missingFiles = parentFiles.filter((f) => !existsSync(f));
  if (missingFiles.length > 0) {
    problems.push(`P300_HIT_PARENT names ${missingFiles.join(', ')}, which ${missingFiles.length === 1 ? 'is' : 'are'} not there.`);
  } else {
    const priors = parentFiles.map((f) => JSON.parse(readFileSync(f, 'utf8')));
    process.stdout.write(
      `\nagainst the parent (${String(priors.length)} run${priors.length === 1 ? '' : 's'}): every reading must be ` +
        "equal or LOWER at HEAD than the parent's worst; a ping-graded delta inside one ping period is not resolved\n"
    );
    process.stdout.write(
      pad('reading', 18) + pad('on', 6) + num('parent band', 20) + num('head', 10) + num('delta', 10) + '  verdict\n'
    );
    process.stdout.write('-'.repeat(120) + '\n');
    for (const r of readings) {
      const key = gradedKey(r.label);
      const ps = priors
        .map((p) => (p.readings ?? []).find((x) => x.label === r.label))
        .filter((p) => p !== undefined && typeof p[key] === 'number');
      if (ps.length === 0) {
        process.stdout.write(pad(r.label, 18) + pad(key === 'wallMs' ? 'wall' : 'ping', 6) + num('-', 20) + num(r[key], 10) + num('-', 10) + '  NO PARENT READING\n');
        problems.push(
          `${r.label}: no parent run has a reading for it, so this one is ungraded. ` +
            'A reading with no floor is a reading that cannot fail.'
        );
        continue;
      }
      const values = ps.map((p) => p[key]);
      const floor = Math.max(...values);
      const low = Math.min(...values);
      const delta = r[key] - floor;
      const resolved = key === 'wallMs' || delta > PING_PERIOD_MS || delta <= 0;
      const worse = delta > 0 && resolved;
      const verdict = worse ? 'WORSE' : delta > 0 ? 'within one ping period, not resolved' : 'equal or better';
      process.stdout.write(
        pad(r.label, 18) +
          pad(key === 'wallMs' ? 'wall' : 'ping', 6) +
          num(values.length === 1 ? String(floor) : `${String(low)}..${String(floor)}`, 20) +
          num(r[key], 10) +
          num(delta.toFixed(2), 10) +
          `  ${verdict}\n`
      );
      if (worse) {
        problems.push(
          `${r.label}: ${String(floor)} ms at the parent's worst and ${String(r[key])} ms at HEAD, graded on the ` +
            `${key === 'wallMs' ? 'wall' : 'drained worst ping'}. The operator's standing rule is that nothing gets ` +
            'worse, and a phase that makes one read fast and another slower has regressed.'
        );
      }
      // AND THE COUNTS. A faster read that changes a count is a regression here.
      // Every parent run must agree with HEAD, and with each other.
      for (const p of ps) {
        if (String(p.counts ?? '') !== String(r.counts ?? '')) {
          problems.push(
            `${r.label}: the counts MOVED. Parent "${String(p.counts)}" and HEAD "${String(r.counts)}". This phase is ` +
              'about time; a changed count belongs to Phase 299 and fails this run whichever way it moved.'
          );
          break;
        }
      }
      // AND THE PIN. The two arms' turn counts must agree on every record.
      for (const p of priors) {
        for (const [size, pin] of Object.entries(p.pins ?? {})) {
          const mine = pins[size];
          if (mine !== undefined && pin.turns !== null && mine.turns !== null && pin.turns !== mine.turns) {
            problems.push(`the ${size} record pinned ${String(pin.turns)} turns at the parent and ${String(mine.turns)} here.`);
          }
        }
      }
    }
  }
} else {
  say(
    'no P300_HIT_PARENT, so nothing here is graded against the parent. The parent-commit ' +
      'measurement is MANDATORY for this phase whatever the tier, and this run has taken one side of it.'
  );
}

const readingsPath = join(outDir, 'readings.json');
writeFileSync(
  readingsPath,
  `${JSON.stringify(
    {
      at: new Date().toISOString(),
      base,
      checkout,
      node: process.version,
      pingPeriodMs: PING_PERIOD_MS,
      sizes,
      claudeDirs,
      pins,
      readings,
      heartbeatWorstMs: report?.heartbeatWorstMs ?? null,
      problems
    },
    null,
    1
  )}\n`
);
say(`readings written to ${readingsPath}`);

if (problems.length > 0) {
  for (const p of problems) process.stderr.write(`${TAG} ${p}\n`);
  process.stderr.write(`${TAG} FAILED: ${String(problems.length)} finding(s).\n`);
  process.exit(1);
}
if (readings.length === 0) {
  process.stderr.write(`${TAG} FAILED: no reading came back, so nothing was measured.\n`);
  process.exit(1);
}
say(`OK: ${String(readings.length)} readings, no count moved, and no reading is worse than the parent's.`);
process.exit(0);
