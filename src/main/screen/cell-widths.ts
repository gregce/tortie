/** The zero-width ranges of plane 14 (U+E0000 to U+E0FFF), measured on tmux 3.7b; see the header. */
const PLANE_14_ZERO: readonly number[] = Object.freeze([
  0xe0001, 0xe0001, 0,
  0xe0020, 0xe007f, 0,
  0xe0100, 0xe01ef, 0
]);

/** The last code point the spec step's scan measured. */
export const SCANNED_LAST = 0x3ffff;

/** The width a flattened table gives `cp`, or null when no range holds it. */
function lookup(table: readonly number[], cp: number): number | null {
  let lo = 0;
  let hi = table.length / 3 - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    const start = table[mid * 3] ?? 0;
    const end = table[mid * 3 + 1] ?? 0;
    if (cp < start) hi = mid - 1;
    else if (cp > end) lo = mid + 1;
    else return table[mid * 3 + 2] ?? null;
  }
  return null;
}

/**
 * A code point's cell width as tmux 3.7b draws it alone: 0 (it joins the cell
 * before it), 1 or 2. A code point no measured range holds (a control, a
 * surrogate, or past the scan but for plane 14's three zero ranges) answers 1.
 */
export function cellWidthOf(cp: number): 0 | 1 | 2 {
  const w = cp <= SCANNED_LAST ? lookup(SCANNED, cp) : lookup(PLANE_14_ZERO, cp);
  return w === 0 ? 0 : w === 2 ? 2 : 1;
}

